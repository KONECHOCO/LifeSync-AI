base = 'ios/LifeSyncAI/Resources/{}.lproj/'
for lang, kv in D.items():
    path = base.format(lang) + 'Localizable.strings'
    text = open(path, encoding='utf-8').read().replace('\r\n', '\n')
    existing = {line.split('"')[1] for line in text.splitlines() if line.startswith('"') and '" = ' in line}
    add = ''.join('"%s" = "%s";\n' % (k, v.replace('"', '\\"')) for k, v in kv.items() if k not in existing)
    if not text.endswith('\n'):
        text += '\n'
    open(path, 'w', encoding='utf-8', newline='\n').write(text + '\n' + add)
    print(lang, 'strings added', len([k for k in kv if k not in existing]))

